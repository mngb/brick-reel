export const GLYPH_W = 5, GLYPH_H = 7;

/** Render lines of text into a boolean grid. Returns {w, h, cells:boolean[][]} */
export function textGrid(lines, { letterGap = 1, lineGap = 1 } = {}) {
  const rows = lines.map((line) => [...line.toUpperCase()].map((ch) => G[ch] ?? G['?']));
  const w = Math.max(...rows.map((r) => r.length * (GLYPH_W + letterGap) - letterGap));
  const h = rows.length * (GLYPH_H + lineGap) - lineGap;
  const cells = Array.from({ length: h }, () => new Array(w).fill(false));

  rows.forEach((glyphs, li) => {
    const lineW = glyphs.length * (GLYPH_W + letterGap) - letterGap;
    const xOff = Math.floor((w - lineW) / 2); // center each line
    const yOff = li * (GLYPH_H + lineGap);
    glyphs.forEach((g, gi) => {
      for (let r = 0; r < GLYPH_H; r++)
        for (let c = 0; c < GLYPH_W; c++)
          if (g[r] & (1 << (GLYPH_W - 1 - c)))
            cells[yOff + r][xOff + gi * (GLYPH_W + letterGap) + c] = true;
    });
  });
  return { w, h, cells };
}
